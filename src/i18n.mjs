export const messages = { en, zh };

export function normalizeLanguage(value) {
  const normalized = String(value ?? '').toLowerCase().replace('_', '-');
  return normalized === 'zh' || normalized === 'zh-cn' ? 'zh' : 'en';
}

export function languageLabel(value) {
  const id = normalizeLanguage(value);
  return languages.find(language => language.id === id)?.label ?? 'English';
}

export function t(language, key, values = {}) {
  const id = normalizeLanguage(language);
  const template = messages[id][key] ?? messages.en[key];
  if (template === undefined) return key;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match);
}

export function statusLabel(language, status) {
  return t(language, `status_${status}`);
}
