const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { palette, theme } = themeFor(0);

const frameOptions = (width, height = FRAME_HEIGHTS[width]) => ({
  width, height, time: FIXED_TIME, now: FIXED_NOW, palette, theme,
});

const selectionState = ui => ({
  runIndex: ui.runIndex,
  selectedRunId: ui.selectedRunId,
  selectedNodeId: ui.selectedNodeId,
  selectedTaskId: ui.selectedTaskId,
  selectedTaskUnlinked: ui.selectedTaskUnlinked,
  runOverview: ui.runOverview,
  focus: ui.focus,
  lastFocus: ui.lastFocus,
  manualScroll: ui.manualScroll,
  follow: ui.follow,
  graphScroll: ui.graphScroll,
  graphScrollTarget: ui.graphScrollTarget,
  runsScroll: ui.runsScroll,
  runsScrollTarget: ui.runsScrollTarget,
  cellsScroll: ui.cellsScroll,
  cellsScrollTarget: ui.cellsScrollTarget,
  folded: [...ui.folded].sort(),
});

const fixtureUi = (overrides = {}) => baseUi({
  selectedRunId: 'run_build',
  selectedNodeId: 'api',
  selectedTaskId: 'st_api',
  ...overrides,
});

// The committed fixtures were generated by the direct pre-boundary renderer.
// Rendering through the view model must reproduce their text and hitboxes
// byte for byte, at every surface, width, and language.
test('the view-model path reproduces the frozen direct-path frame on every golden fixture', () => {
  for (const surface of FRAME_SURFACES) {
    for (const width of FRAME_WIDTHS) {
      const height = FRAME_HEIGHTS[width];
      for (const language of FRAME_LANGUAGES) {
        const name = `${surface}.${width}x${height}.${language}.json`;
        const fixture = loadFrameFixture(surface, language, width, height);
        const vm = buildViewModel(frameSnapshot(), frameUi(surface, language));
        const frame = renderApp(vm, frameOptions(width, height));
        assert.equal(vm.frame, null, `${name}: render must not write vm.frame`);
        attachFrame(vm, frame);
        assert.equal(vm.frame, frame, `${name}: attachFrame is the frame writer`);
        assert.deepEqual(
          serializeFrame(frame, { surface, language, width, height }),
          fixture,
          `${name}: view-model frame differs from the frozen direct path`,
        );
        assert.equal(
          compareFrame(fixture, frame), null,
          `${name}: view-model text or hitbox differs from the frozen direct path`,
        );
        const direct = renderFixtureFrame(surface, language, width, height);
        assert.deepEqual(
          serializeFrame(frame, { surface, language, width, height }),
          serializeFrame(direct, { surface, language, width, height }),
          `${name}: VM-path and direct-call frames differ`,
        );
      }
    }
  }
});

test('view-model selection wrappers match the direct reducer path', () => {
  const snapshot = frameSnapshot();

  const directUi = fixtureUi();
  const directVm = buildViewModel(snapshot, fixtureUi());
  assert.deepEqual(
    selectTask(directVm, 'st_tests'),
    selectTaskHit(directUi, snapshot, 'st_tests'),
  );
  assert.deepEqual(selectionState(directVm.ui), selectionState(directUi));

  const runUi = fixtureUi();
  const runVm = buildViewModel(snapshot, fixtureUi());
  assert.equal(selectRun(runVm, 'run_docs'), selectRunById(runUi, snapshot, 'run_docs'));
  assert.deepEqual(selectionState(runVm.ui), selectionState(runUi));

  const overviewUi = fixtureUi();
  const overviewVm = buildViewModel(snapshot, fixtureUi());
  assert.equal(
    selectRun(overviewVm, 'run_docs', { overview: true }),
    selectRunOverview(overviewUi, snapshot, 'run_docs'),
  );
  assert.deepEqual(selectionState(overviewVm.ui), selectionState(overviewUi));

  const nodeUi = fixtureUi({ focus: 'graph' });
  const nodeVm = buildViewModel(snapshot, fixtureUi({ focus: 'graph' }));
  selectNode(nodeVm, 1, { scrollInfo: {}, structural: undefined });
  selectNodeUi(nodeUi, snapshot, 1, { scrollInfo: {}, structural: undefined });
  assert.deepEqual(selectionState(nodeVm.ui), selectionState(nodeUi));

  const metrics = { runs: { viewportH: 1 }, cells: { viewportH: 0 }, details: { viewportH: 10 } };
  const focusUi = fixtureUi({ focus: 'graph' });
  const focusVm = buildViewModel(snapshot, fixtureUi({ focus: 'graph' }));
  assert.equal(
    applyFocus(focusVm, 'runs', 'duty', metrics),
    applyFocusRequest(focusUi, 'runs', 'duty', metrics),
  );
  assert.deepEqual(selectionState(focusVm.ui), selectionState(focusUi));
});

test('toggleFold moves only the selected graph node and reports the write policy', () => {
  const snapshot = frameSnapshot();
  const vm = buildViewModel(snapshot, fixtureUi({ focus: 'graph', foldedByRun: new Map() }));
  const writes = [];
  assert.equal(toggleFold(vm, { persist: (...args) => writes.push(args) }), true);
  assert.deepEqual([...vm.ui.folded], ['api']);
  assert.deepEqual(vm.ui.foldedByRun.get('run_build'), new Set(['api']));
  assert.equal(vm.ui.follow, false);
  assert.equal(vm.ui.manualScroll, false);
  assert.deepEqual(writes, [['run_build', 'api', false]]);

  assert.equal(toggleFold(vm, { persist: (...args) => writes.push(args) }), true);
  assert.deepEqual([...vm.ui.folded], []);
  assert.deepEqual(writes.at(-1), ['run_build', 'api', true]);

  const unfocused = buildViewModel(snapshot, fixtureUi({ focus: 'tasks' }));
  assert.equal(toggleFold(unfocused), false, 'a non-graph focus never folds');
});

test('hitTargetAt resolves painted subjects and refuses a missing subject', () => {
  const snapshot = frameSnapshot();
  const vm = buildViewModel(snapshot, fixtureUi());
  const frame = attachFrame(vm, renderApp(vm, frameOptions(120, 40)));

  const taskRect = frame.hitboxes.tasks.get('st_api');
  assert.ok(taskRect, 'the task row is painted');
  assert.deepEqual(hitTargetAt(vm, taskRect.x + 1, taskRect.y), { kind: 'task', id: 'st_api' });

  const nodeRect = frame.hitboxes.nodes.get('api');
  assert.ok(nodeRect, 'the graph node is painted');
  assert.equal(hitTargetAt(vm, nodeRect.x, nodeRect.y)?.kind, 'node');
  assert.equal(hitTargetAt(vm, nodeRect.x, nodeRect.y)?.id, 'api');

  const runRect = frame.hitboxes.runs.get('run_docs');
  assert.ok(runRect, 'the run row is painted');
  assert.deepEqual(hitTargetAt(vm, runRect.x, runRect.y), { kind: 'run', id: 'run_docs' });

  // A missing id is not a moved target: the reducers refuse it and the VM keeps
  // the previous selection for the next frame.
  const before = selectionState(vm.ui);
  assert.equal(selectRun(vm, 'run_missing'), false);
  assert.deepEqual(selectTask(vm, 'st_missing'), { handled: false, linked: undefined });
  assert.deepEqual(selectionState(vm.ui), before);
  const empty = buildViewModel(
    { ...snapshot, runs: [{ ...snapshot.runs[0], nodes: [] }] },
    fixtureUi(),
  );
  assert.equal(selectNode(empty, 1), undefined, 'a run without nodes has no target to move to');

  // Removing the painted subject makes its old cell resolve to whatever is
  // painted there now (or null), never to the vanished id.
  const reduced = {
    ...snapshot,
    runs: snapshot.runs.filter(run => run.id !== 'run_build'),
    tasks: snapshot.tasks.filter(task => task.id !== 'st_api'),
  };
  reconcile(vm, { snapshot: reduced });
  assert.equal(selectRun(vm, 'run_build'), false);
  assert.deepEqual(selectTask(vm, 'st_api'), { handled: false, linked: undefined });
  const stale = hitTargetAt(vm, taskRect.x + 1, taskRect.y);
  assert.ok(!stale || stale.id !== 'st_api', 'the stale task id never wins the pointer');
  assert.equal(hitTargetAt(vm, nodeRect.x, nodeRect.y), null, 'the removed node cell is empty');
});

test('settleScroll advances only painted regions and clamps the graph target', () => {
  const vm = buildViewModel(frameSnapshot(), fixtureUi());
  const frame = attachFrame(vm, renderApp(vm, frameOptions(120, 40)));
  const { ui } = vm;
  ui.graphScrollTarget = 999;
  ui.graphScroll = 999;
  ui.tasksScrollTarget = 999;
  ui.tasksScroll = 0;
  ui.runsScrollTarget = 3;
  ui.runsScroll = 0;
  ui.detailsScrollTarget = 999;
  ui.detailsScroll = 0;

  settleScroll(vm, frame, { elapsed: 100, interactive: true });

  assert.equal(ui.graphScrollTarget, frame.scroll.graph.maxScroll);
  assert.equal(ui.graphScroll, frame.scroll.graph.maxScroll);
  assert.equal(ui.tasksScrollTarget, frame.scroll.tasks.maxScroll);
  assert.equal(ui.tasksScroll, 0, 'a one-cell viewport has no room to scroll');
  assert.equal(ui.runsScroll, 0, 'unpainted run metrics keep their offset');
  assert.equal(ui.detailsScrollTarget, frame.scroll.details.maxScroll);
  assert.ok(ui.detailsScroll >= 0 && ui.detailsScroll <= frame.scroll.details.maxScroll);
  assert.equal(
    ui.detailsScroll > 0,
    frame.scroll.details.maxScroll > 0,
    'details ease away from the top only when the frame can scroll',
  );
});

test('the boundary owns the frame and never leaks hitboxes onto ui', async () => {
  const vm = buildViewModel(frameSnapshot(), fixtureUi());
  const frame = renderApp(vm, frameOptions(120, 40));
  assert.equal(vm.frame, null);
  assert.equal(Object.hasOwn(vm.ui, 'hitboxes'), false);
  attachFrame(vm, frame);
  assert.equal(vm.frame, frame);
  assert.equal(Object.hasOwn(vm.ui, 'hitboxes'), false);

  const [renderText, viewerText, modelText] = await Promise.all([
    readFile(resolve(root, 'src/render.mjs'), 'utf8'),
    readFile(resolve(root, 'src/viewer.mjs'), 'utf8'),
    readFile(resolve(root, 'src/view-model.mjs'), 'utf8'),
  ]);
  assert.doesNotMatch(renderText, /from\s+['"]\.\/viewer\.mjs['"]/, 'render never imports the viewer');
  assert.doesNotMatch(viewerText, /ui\.hitboxes\b/, 'the viewer never stores hitboxes on ui');
  assert.equal(
    (viewerText.match(/vm\.frame\s*=/g) ?? []).length,
    0,
    'the viewer never writes vm.frame directly',
  );
  assert.equal(
    (modelText.match(/vm\.frame\s*=/g) ?? []).length,
    1,
    'only attachFrame writes vm.frame',
  );
});
